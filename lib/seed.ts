/* The bundled example: an invented family.
 *
 * This is filler, and it is meant to be. Its only job is to give somebody
 * opening the app for the first time something to tap around in before they
 * start their own tree, so it is deliberately ordinary - a made-up Punjabi
 * family across five generations, with nobody real in it and nothing to get
 * wrong. Change it freely.
 *
 * It is shaped to exercise every part of the interface rather than to be big:
 *
 *  - five generations, so "Whole tree" has something to scroll
 *  - `Abdul Karim` has two wives, so the spouse list on a card is not
 *    hypothetical
 *  - `Tariq Mahmood` married in and has no recorded parents, so his children
 *    hang under their mother - the `buildTree` fallback in lib/layout.ts that
 *    keeps grandchildren attached
 *  - `Shabbir` never married and `Nadia` has no children, so empty slots show
 *  - dates are written several different ways, because they are free text and
 *    nothing parses them
 *
 * Every name has an Urdu spelling beside the Latin one; notes stay in English.
 * -------------------------------------------------------------------------- */
