export function buildSampleTree(): Tree {
  const now = new Date().toISOString();
  return {
    id: SAMPLE_TREE_ID,
    name: 'The Malik Family',
    nameUr: 'ملک خاندان',
    note: 'An example family, invented to show how the app works. Nobody in it is real - change anything you like, or remove the whole family when you are finished with it.',
    rootId: 'ghulam-rasool',
    // Opens on somebody with parents, a wife, children and brothers and sisters,
    // so the Family view has every slot filled the first time it is seen.
    focusId: 'bilal',
    createdAt: now,
    updatedAt: now,
    isSample: true,
    people: SAMPLE_PEOPLE.map((p) => ({ ...p, spouseIds: [...p.spouseIds] })),
  };
}
